    private static readonly FrozenDictionary<(string Name, int DialingCode), string> ByName
        = Rows.ToFrozenDictionary(row => (row.Name, row.DialingCode), row => row.Flag);

    private static readonly FrozenDictionary<(int Id, int DialingCode), string> ById
        = Rows.ToFrozenDictionary(row => (row.Id, row.DialingCode), row => row.Flag);

    /// <summary>
    /// The flag image of an entry, or <c>null</c> when the entry is not a known one.
    /// </summary>
    public static Uri? Find(BiliLoginCountry country)
    {
        // By name first, so that renumbered entries keep their flags; by id for an entry that was only renamed.
        // The dialing code has to agree either way.
        if (!ByName.TryGetValue((country.Name.Trim(), country.DialingCode), out var flag)
            && !ById.TryGetValue((country.Id, country.DialingCode), out flag))
        {
            return null;
        }

        return new Uri($"ms-appx:///Assets/Flags/{flag}.png");
    }
